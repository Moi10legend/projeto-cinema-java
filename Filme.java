public class Filme{
    private String nome;
    private String sinopse;
    private int duracao;  //Em minutos
    private double valor;

    public Filme(String nome, String sinopse, int duracao, double valor){
        this.nome = nome;
        this.sinopse = sinopse;
        this.duracao = duracao;
        this.valor = valor;
    }
}